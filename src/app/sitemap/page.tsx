import type { Metadata } from "next";
import Link from "next/link";
import { site } from "@/lib/config";
import { absolute } from "@/lib/seo";
import { SITEMAPS } from "@/lib/sitemaps";
import SitemapFilter from "./SitemapFilter";

// Human-readable sitemap, styled like /sitemap.xml (which browsers are dropping XSLT support for).
export const metadata: Metadata = {
  title: `Sitemap | ${site.name}`,
  description: `All public pages on ${site.name}.`,
  alternates: { canonical: absolute("/sitemap") },
};

const GROUP_NAMES: Record<string, string> = { page: "Pages", legal: "Legal" };

export default function SitemapPage() {
  const total = Object.values(SITEMAPS).reduce((n, g) => n + g.length, 0);
  return (
    <div className="min-h-screen bg-[#f4f4f2] text-[15px] text-[#17181b]">
      <header className="border-b-[3px] border-[#c9ccd2] bg-gradient-to-b from-[#111215] to-[#050506] py-7 text-white">
        <div className="mx-auto max-w-[1040px] px-6">
          <Link href="/" className="flex items-center gap-3 text-[22px] font-semibold tracking-tight">
            {/* eslint-disable-next-line @next/next/no-img-element -- small static logo */}
            <img src="/logo.png" alt="" width={36} height={36} /> {site.name}
          </Link>
          <h1 className="mt-5 mb-1.5 text-[26px] font-semibold tracking-tight">Sitemap</h1>
          <p className="max-w-[560px] text-sm text-[#c7c9ce]">
            All public pages on {site.name}. Search engines use the{" "}
            <a href="/sitemap.xml" className="text-white underline decoration-dotted underline-offset-[3px]">XML sitemap</a>.
          </p>
        </div>
      </header>
      <main className="mx-auto max-w-[1040px] px-6" data-sitemap>
        <div className="mt-7 mb-4 flex flex-wrap items-center justify-between gap-3">
          <p className="text-[#6b6e75]">
            This sitemap lists <strong className="text-[#17181b]">{total}</strong> pages.
          </p>
          <SitemapFilter placeholder="Filter pages…" />
        </div>
        {Object.entries(SITEMAPS).map(([group, pages]) => (
          <section key={group} className="mb-6">
            <h2 className="mb-2 text-sm font-semibold uppercase tracking-[0.08em] text-[#6b6e75]">{GROUP_NAMES[group] ?? group}</h2>
            <div className="overflow-hidden rounded-[14px] border border-[#e4e4e0] bg-white">
              <table className="w-full border-separate border-spacing-0">
                <thead>
                  <tr className="bg-[#0b0c0e] text-left text-[11px] uppercase tracking-[0.08em] text-white">
                    <th className="px-[18px] py-3.5 font-semibold">URL</th>
                    <th className="hidden px-[18px] py-3.5 text-right font-semibold sm:table-cell">Priority</th>
                    <th className="hidden px-[18px] py-3.5 text-right font-semibold sm:table-cell">Change frequency</th>
                    <th className="px-[18px] py-3.5 text-right font-semibold">Last modified</th>
                  </tr>
                </thead>
                <tbody>
                  {pages.map((p) => (
                    <tr key={p.path} className="even:bg-[#fafaf8]">
                      <td className="border-t border-[#e4e4e0] px-[18px] py-3">
                        <Link href={p.path} className="break-all text-[#2f7d5b] hover:underline">{absolute(p.path)}</Link>
                      </td>
                      <td className="hidden border-t border-[#e4e4e0] px-[18px] py-3 text-right text-[#6b6e75] sm:table-cell">{p.priority.toFixed(1)}</td>
                      <td className="hidden border-t border-[#e4e4e0] px-[18px] py-3 text-right text-[#6b6e75] sm:table-cell">{p.changefreq}</td>
                      <td className="whitespace-nowrap border-t border-[#e4e4e0] px-[18px] py-3 text-right text-[#6b6e75]">{p.updated}</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          </section>
        ))}
        <footer className="mt-4 pb-12 text-xs text-[#6b6e75]">
          Generated by {site.name}. <a href="/sitemap.xml" className="underline">XML sitemap</a> · <Link href="/" className="underline">{site.domain}</Link>
        </footer>
      </main>
    </div>
  );
}
